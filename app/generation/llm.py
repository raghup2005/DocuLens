import ollama


class LLM:
    """
    Handles communication with the local Ollama LLM.
    Supports text, table, and image-derived context.
    """

    def __init__(
        self,
        model_name: str = "llama3.2:3b"
    ):
        self.model_name = model_name

    def generate(
        self,
        query: str,
        context: str
    ) -> str:
        """
        Generate an answer using retrieved multimodal context.

        Image records are represented by text descriptions
        generated by the vision model.
        """

        if not query.strip():
            raise ValueError(
                "Query cannot be empty."
            )

        if not context.strip():
            raise ValueError(
                "Context cannot be empty."
            )

        prompt = f"""
You are a Retrieval-Augmented Generation assistant.

You are given retrieved evidence from documents.

The evidence may come from:
- text extracted from documents
- tables converted into text
- images described by a vision model

Treat image descriptions as evidence about what is visible
in the original image.

Answer the user's question using the retrieved evidence.

Rules:
1. Answer directly when the evidence contains the answer.
2. Use all relevant contexts, not just the first one.
3. Do not invent facts that are not supported by the evidence.
4. Do not reject an answer merely because the evidence came
   from an image description.
5. When the evidence is sufficient, give a concise explanation.
6. Only say that there is not enough information when the
   retrieved evidence genuinely cannot answer the question.

RETRIEVED EVIDENCE:
==================================================
{context}
==================================================

USER QUESTION:
{query}

Now answer the question using the retrieved evidence.

ANSWER:
"""

        response = ollama.chat(
            model=self.model_name,
            messages=[
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            options={
                "temperature": 0
            }
        )

        return response[
            "message"
        ]["content"].strip()


if __name__ == "__main__":

    llm = LLM()

    context = """
Context 1:
Content Type: image
Source: 1706.03762v7.pdf
Page: 4

Content:
The diagram shows the scaled dot-product attention
operation. It contains Q, K, and V, followed by
matrix multiplication, scaling, optional masking,
softmax, and a final multiplication with V.
"""

    query = "What does the attention diagram show?"

    answer = llm.generate(
        query=query,
        context=context
    )

    print("\nGenerated Answer:\n")
    print(answer)